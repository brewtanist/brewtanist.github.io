"""Offline DOM-injection regression test for user-authored OEM text and RFQ import.

Uses a local built website with all external requests aborted. It never posts
to production, opens a staff session, or writes to the OEM backend.
A harmless marker tests whether untrusted HTML strings execute in the browser.
"""
from __future__ import annotations

import argparse
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
import json
from pathlib import Path
import threading
from urllib.parse import urlsplit

from playwright.sync_api import expect, sync_playwright

ROUTES = {
    "th": ("/oem/", "/admin/quotes/"),
    "en": ("/en/oem/", "/en/admin/quotes/"),
    "zh": ("/zh/oem/", "/zh/admin/quotes/"),
}
MARKER = '<img src=x onerror="window.__brewtanist_injection=1">'


class Quiet(SimpleHTTPRequestHandler):
    def log_message(self, *args):
        return


def test(build: Path):
    server = ThreadingHTTPServer(("127.0.0.1", 0), partial(Quiet, directory=str(build)))
    threading.Thread(target=server.serve_forever, daemon=True).start()
    origin = "http://127.0.0.1:" + str(server.server_address[1])
    results = []
    try:
        with sync_playwright() as playwright:
            for engine in ("chromium", "webkit"):
                browser = getattr(playwright, engine).launch()
                for lang, (form_path, desk_path) in ROUTES.items():
                    customer = browser.new_page(accept_downloads=True)
                    errors = []
                    customer.on("pageerror", lambda error: errors.append(str(error)))

                    # Explicitly deny network access outside the temporary localhost
                    # server. No live OEM request can be generated by this test.
                    def only_local(route):
                        u = urlsplit(route.request.url)
                        if u.scheme == "http" and u.netloc == urlsplit(origin).netloc:
                            route.continue_()
                        else:
                            route.abort()

                    customer.route("**/*", only_local)
                    customer.goto(origin + form_path, wait_until="domcontentloaded")
                    customer.locator('[name="beanQuantity"]').fill("2.5")
                    customer.locator('[name="name"]').fill("QA Non-Production")
                    customer.locator('[name="email"]').fill("qa@example.invalid")
                    customer.locator('[name="company"]').fill("QA " + MARKER)
                    customer.locator('[name="flavour"]').fill(MARKER)
                    customer.locator('[name="notes"]').fill(MARKER)
                    customer.locator("#oem-form button[type=submit]").click()
                    expect(customer.locator("#oem-review")).to_be_visible()
                    assert MARKER in customer.locator("#oem-summary").input_value()
                    assert customer.locator('img[src="x"]').count() == 0
                    assert customer.evaluate("window.__brewtanist_injection === undefined")
                    with customer.expect_download() as result:
                        customer.locator("#oem-download").click()
                    rfq = json.loads(Path(result.value.path()).read_text(encoding="utf-8"))
                    assert rfq["project"]["flavour"] == MARKER
                    assert rfq["project"]["notes"] == MARKER
                    assert rfq["contact"]["company"] == "QA " + MARKER

                    desk = browser.new_page()
                    desk.route("**/*", only_local)
                    desk.on("pageerror", lambda error: errors.append(str(error)))
                    desk.goto(origin + desk_path, wait_until="domcontentloaded")
                    expect(desk.locator("#quote-app")).to_be_visible()
                    desk.locator("#file").set_input_files({
                        "name": "qa-untrusted-rfq.json",
                        "mimeType": "application/json",
                        "buffer": json.dumps(rfq, ensure_ascii=False).encode("utf-8"),
                    })
                    expect(desk.locator('input[name="company"]')).to_have_value("QA " + MARKER)
                    expect(desk.locator("#source-list")).to_contain_text(MARKER)
                    assert desk.locator('img[src="x"]').count() == 0
                    assert desk.evaluate("window.__brewtanist_injection === undefined")
                    assert not errors, errors
                    customer.close()
                    desk.close()
                    results.append(engine + " " + lang + ": untrusted form/RFQ text remains inert")
                browser.close()
    finally:
        server.shutdown()
        server.server_close()
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("build", type=Path)
    args = parser.parse_args()
    for item in test(args.build.resolve()):
        print("PASS: " + item, flush=True)


if __name__ == "__main__":
    main()
